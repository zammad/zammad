class Integration::IdoitUpController < ApplicationController
  prepend_before_action :authenticate_and_authorize!

  SENSITIVE_FIELDS = [:api_token].freeze

  def verify
    unmasked_params = unmask_sensitive_params(params, Setting.get('idoit_up_config'))

    response = ::IdoitUp.verify(unmasked_params[:api_token], unmasked_params[:endpoint], unmasked_params[:client_id],
                                verify_ssl: unmasked_params[:verify_ssl], user: current_user)

    render json: {
      result:   'ok',
      response: response,
    }
  rescue => e
    logger.error e

    render json: {
      result:  'failed',
      message: e.message,
    }
  end

  def query
    response = ::IdoitUp.query(params[:method], params[:filter],
                               limit: params[:limit], offset: params[:offset], user: current_user)
    render json: {
      result:   'ok',
      response: response,
    }
  rescue => e
    logger.error e

    render json: {
      result:  'failed',
      message: e.message,
    }
  end

  def update
    params[:object_ids] ||= []
    ticket = Ticket.find(params[:ticket_id])
    ticket.with_lock do
      authorize!(ticket, :show?)
      ticket.preferences[:idoit_up] ||= {}
      ticket.preferences[:idoit_up][:object_ids] = Array(params[:object_ids]).uniq
      ticket.save!
    end

    render json: {
      result: 'ok',
    }
  end

  def logo
    render json: {
      result: 'ok',
      svg:    LOGO_SVG,
    }
  end

